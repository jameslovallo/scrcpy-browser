    public static IntPtr FindTopLevelWindowByTitle(string title)
    {
        var found = IntPtr.Zero;
        var buffer = new StringBuilder(512);
        EnumWindows((hWnd, _) =>
        {
            buffer.Clear();
            GetWindowText(hWnd, buffer, buffer.Capacity);
            if (buffer.ToString() == title)
            {
                found = hWnd;
                return false;
            }
            return true;
        }, IntPtr.Zero);
        return found;
    }
